from generate_river_access import surface_polygon,shape,sub,dot,cross,norm
import shapely
ROOT=Path(__file__).resolve().parents[1]
def generate():
 raw=json.loads((ROOT/'data/geometry.json').read_text());garden=json.loads((ROOT/'data/wintergarden_plan.json').read_text());cut=shape(garden['metadata']['roofFootprintStuds']).buffer(-.6)
 records=[];guards=[];removed=[]
 for index,r in enumerate(raw):
  if r['name']!='JoinedRoad':continue
  poly=surface_polygon(r);inside=poly.intersection(cut)
  if inside.area<1e-6:continue
  outside=poly.difference(cut);guards.append(dict(sourceIndex=index,record=r));removed.append(inside)
  top=r['pos'][1]+sum(abs(r['matrix'][3+i])*r['size'][i]/2 for i in range(3));depth=r['size'][0]
  triangles=list(shapely.constrained_delaunay_triangles(outside).geoms);assert abs(sum(t.area for t in triangles)-outside.area)<1e-5
  for tri in triangles:
   a,b,c=[[x,top-depth/2,z]for x,z in list(tri.exterior.coords)[:3]];ab,ac,bc=sub(b,a),sub(c,a),sub(c,b)
   if dot(ab,ab)>dot(ac,ac)and dot(ab,ab)>dot(bc,bc):c,a=a,c
   elif dot(ac,ac)>dot(bc,bc):a,b=b,a
   ab,ac,bc=sub(b,a),sub(c,a),sub(c,b);right=norm(cross(ac,ab));back=norm(bc);up=norm(cross(bc,right));width=abs(dot(ab,up))
   for other,v,flip in[(b,ab,1),(c,ac,-1)]:
    length=abs(dot(v,back))
    if min(width,length)<.001:continue
    m=[right[0]*flip,up[0],back[0]*flip,right[1]*flip,up[1],back[1]*flip,right[2]*flip,up[2],back[2]*flip]
    records.append(dict(name='AtriumRepair_PreservedExteriorRoad',size=[depth,width,length],pos=[(a[i]+other[i])/2 for i in range(3)],matrix=m,color=r['color'],material=r['material'],collide=True,cls='WedgePart'))
 assert len(guards)==2 and len(records)<=40
 return dict(id='WintergardenFloorRepair',records=records,guards=guards,cutPolygon=shapely.to_geojson(cut),interiorArea=sum(p.area for p in removed),floorTop=garden['metadata']['floorTopStuds'])
