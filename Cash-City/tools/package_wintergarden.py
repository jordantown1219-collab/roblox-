"""Package reviewed Wintergarden data; never changes the source geography."""
import json
from pathlib import Path
P=Path(__file__).resolve().parents[1]
def package():
    return json.loads((P/'data/wintergarden_plan.json').read_text())
if __name__=='__main__':
    payload=json.dumps(package(),separators=(',',':'),allow_nan=False)
    (P/'src/WintergardenData.lua').write_text('-- Generated by tools/package_wintergarden.py\nreturn game:GetService("HttpService"):JSONDecode([=['+payload+']=])\n')
    print('Packaged Wintergarden source guards, roof, room and access data')
