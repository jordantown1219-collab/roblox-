"""Package reviewed generators for both the native assembly and saved place."""
from pathlib import Path
import json
P=Path(__file__).resolve().parents[1]
def package():
    towers=json.loads((P/'data/rencen_detail_plan.json').read_text())
    walk=json.loads((P/'data/rencen_walk_plan.json').read_text())
    keys=('name','pos','size','matrix','collide','color','material','trans')
    def compact(record):
        return {k:([round(v,7) for v in value] if isinstance(value,list) else value)
                for k,value in record.items() if k in keys}
    finishes={entry['sourceIndex']:entry for entry in towers['sourceFinishChanges']}
    guards=[]
    for face in towers['faces']:
        guard={'record':compact(face['record'])}
        if face['sourceIndex'] in finishes:
            entry=finishes[face['sourceIndex']]
            guard['finish']={'color':entry['color'],'material':entry['material']}
        guards.append(guard)
    # Original atrium grid is superseded by the reviewed barrel-vault reconstruction.
    return {'guards':guards,'towers':{'id':'RenCenExteriorDetails','records':[compact(r) for r in towers['details'] if r.get('osm')!=419447156]},
            'walk':{'id':walk['id'],'records':[compact(r) for r in walk['records']],'referenceStatus':walk['referenceStatus']}}
if __name__=='__main__':
    payload=json.dumps(package(),separators=(',',':'),allow_nan=False)
    (P/'src/RenaissanceData.lua').write_text('-- Generated by tools/package_renaissance.py\nreturn game:GetService("HttpService"):JSONDecode([=['+payload+']=])\n')
    print('Packaged guarded tower and promenade records')
